#!/usr/bin/env node
/**
 * Generates the reference pages under content/docs/reference/ from the source code.
 *
 * Why generated: these tables (env vars, queues, tables, capabilities, routes)
 * change as the code changes. Writing them by hand makes them drift. Re-run
 * `npm run generate` after code changes. Output has no timestamps, so an
 * unchanged codebase produces no git diff.
 *
 * Reads only. Never writes outside content/docs/reference/.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, sep, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(here, '..');
const repoRoot = resolve(docsRoot, '..');
const backend = join(repoRoot, 'nsgdp-backend');
const frontend = join(repoRoot, 'nsgdp-frontend');
const admin = join(repoRoot, 'nsgdp-admin');
const outDir = join(docsRoot, 'src', 'content', 'docs', 'reference');

/** Escape text for an MDX table cell. */
function cell(value) {
  return String(value ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\{/g, '\\{')
    .replace(/\}/g, '\\}')
    .replace(/</g, '&lt;')
    .replace(/\n+/g, ' ')
    .trim() || '—';
}

function table(headers, rows) {
  const head = `| ${headers.map(cell).join(' | ')} |`;
  const sep2 = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map(cell).join(' | ')} |`);
  return [head, sep2, ...body].join('\n');
}

function walk(dir, predicate, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist' || name.startsWith('.')) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, predicate, out);
    else if (predicate(full)) out.push(full);
  }
  return out;
}

const posix = (p) => p.split(sep).join('/');
const isSource = (f) => f.endsWith('.ts') && !f.endsWith('.spec.ts') && !f.endsWith('.d.ts');

function frontmatter(title, description) {
  return `---\ntitle: ${title}\ndescription: ${description}\n---\n\n{/* Generated by scripts/generate-reference.mjs. Do not edit by hand. */}\n`;
}

// ---------------------------------------------------------------- env vars

function parseComment(lines, index) {
  // Collect the comment block directly above a declaration.
  const collected = [];
  let i = index - 1;
  // Decorators (@IsOptional etc.) sit between the comment and the property.
  while (i >= 0 && /^\s*[@)]/.test(lines[i])) i--;
  while (i >= 0) {
    const line = lines[i].trim();
    if (line.startsWith('//')) {
      collected.unshift(line.replace(/^\/\/\s?/, ''));
    } else if (line.endsWith('*/')) {
      const block = [];
      while (i >= 0 && !lines[i].trim().startsWith('/**') && !lines[i].trim().startsWith('/*')) {
        block.unshift(lines[i].trim().replace(/^\*\s?/, '').replace(/\*\/$/, ''));
        i--;
      }
      if (i >= 0) block.unshift(lines[i].trim().replace(/^\/\*\*?\s?/, ''));
      collected.unshift(...block.filter(Boolean));
      break;
    } else {
      break;
    }
    i--;
  }
  return collected.join(' ').trim();
}

function area(name) {
  const rules = [
    [/^DATABASE_/, 'Database'],
    [/^REDIS_/, 'Redis'],
    [/^STORAGE_|^B2_|^S3_/, 'File storage'],
    [/^JWT_|^ADMIN_(ACCESS|REFRESH|IP|MFA)|^MFA_/, 'Authentication'],
    [/^SMTP_|^EMAIL_|^RESEND_|^BREVO_/, 'Email'],
    [/^TERMII_|^SMS_/, 'SMS'],
    [/^SENTRY_/, 'Error monitoring'],
    [/^ANTHROPIC_|^AI_|^EMBEDDING_|^TRANSFORMERS_/, 'AI assistant and embeddings'],
    [/^CLAMAV_|^MAX_FILE/, 'Uploads and virus scanning'],
    [/^CORS_|^THROTTLE_|^LOGIN_LOCKOUT_|^ENABLE_/, 'Security and limits'],
    [/^LOG_|^NODE_ENV$|^ROLE$|^PORT$|^API_URL$/, 'Runtime'],
  ];
  for (const [re, label] of rules) if (re.test(name)) return label;
  return 'Other';
}

const SECRET_PATTERN = /SECRET|PASSWORD|API_KEY|APPLICATION_KEY|DSN/;

function buildEnvPage() {
  const validationFile = join(backend, 'src', 'config', 'env.validation.ts');
  const lines = readFileSync(validationFile, 'utf8').split(/\r?\n/);
  const declared = new Map();
  lines.forEach((line, idx) => {
    const m = line.match(/^\s{2}([A-Z][A-Z0-9_]*)([!?]):\s*([^;]+);/);
    if (m) {
      declared.set(m[1], {
        required: m[2] === '!',
        type: m[3].trim(),
        description: parseComment(lines, idx),
      });
    }
  });

  // Names read in code, with their literal default when one is given.
  const referenced = new Map();
  const refPattern =
    /(?:process\.env\.([A-Z][A-Z0-9_]+))|(?:\.get(?:<[^>]*>)?\(\s*['"`]([A-Z][A-Z0-9_]{2,})['"`](?:\s*,\s*([^,)]+?))?\s*[,)])/g;
  for (const file of walk(join(backend, 'src'), isSource)) {
    if (file.endsWith(join('config', 'env.validation.ts'))) continue;
    const text = readFileSync(file, 'utf8');
    let m;
    while ((m = refPattern.exec(text))) {
      const name = m[1] ?? m[2];
      const def = m[1] ? undefined : m[3];
      const entry = referenced.get(name) ?? { files: new Set(), defaults: new Set() };
      entry.files.add(posix(relative(backend, file)));
      if (def) entry.defaults.add(def.trim());
      referenced.set(name, entry);
    }
  }

  const names = [...new Set([...declared.keys(), ...referenced.keys()])].sort();
  const rows = names.map((name) => {
    const d = declared.get(name);
    const r = referenced.get(name);
    const secret = SECRET_PATTERN.test(name) ? 'Yes' : 'No';
    return [
      `\`${name}\``,
      area(name),
      d ? (d.required ? 'Yes' : 'No') : 'Optional (read in code)',
      secret,
      r && r.defaults.size ? [...r.defaults].map((x) => `\`${x}\``).join(', ') : d ? '' : '',
      d?.description || '',
    ];
  });

  const body = [
    frontmatter(
      'Environment variables',
      'Every environment variable the backend reads, with area, whether required, and whether it holds a secret.',
    ),
    `Generated from \`nsgdp-backend/src/config/env.validation.ts\` and from every \`process.env\` / \`configService.get\` call in \`nsgdp-backend/src\`. **${names.length} variables.** Values are never listed here. Secrets belong in the server's environment file, not in git.\n`,
    `"Required" means the validator rejects startup when the variable is missing. "Optional (read in code)" means the code reads it, but the validator does not declare it.\n`,
    table(['Variable', 'Area', 'Required', 'Secret', 'Code default', 'Meaning (from source comment)'], rows),
    '',
  ].join('\n');

  return { name: 'env.mdx', body, count: names.length };
}

// ----------------------------------------------------------------- queues

function buildQueuesPage() {
  const file = join(backend, 'src', 'config', 'bull.config.ts');
  const text = readFileSync(file, 'utf8');
  const lines = text.split(/\r?\n/);

  const nameBlock = text.match(/export const QUEUE_NAMES = \{([\s\S]*?)\} as const;/)[1];
  const queueNames = {};
  for (const m of nameBlock.matchAll(/^\s+([A-Z_]+):\s*'([^']+)'/gm)) queueNames[m[1]] = m[2];

  const priorityBlock = text.match(/export const JOB_PRIORITY = \{([\s\S]*?)\} as const;/)[1];
  const priorities = {};
  for (const m of priorityBlock.matchAll(/([A-Z]+):\s*(\d+)/g)) priorities[m[1]] = Number(m[2]);

  const topology = {};
  for (const m of text.matchAll(/\[QUEUE_NAMES\.([A-Z_]+)\]:\s*\{([\s\S]*?)\n  \},/g)) {
    const body = m[2];
    const num = (key) => {
      const v = body.match(new RegExp(`${key}:\\s*([^,\\n]+)`));
      if (!v) return '';
      const raw = v[1].trim();
      const pr = raw.match(/JOB_PRIORITY\.([A-Z]+)/);
      if (pr) return `${priorities[pr[1]]} (${pr[1].toLowerCase()})`;
      const mc = raw.match(/MAX_JOB_ATTEMPTS/);
      if (mc) return '3 (MAX_JOB_ATTEMPTS)';
      return raw;
    };
    // Walk up from the entry to collect the purpose comment.
    const idx = lines.findIndex((l) => l.includes(`[QUEUE_NAMES.${m[1]}]: {`));
    const purpose = [];
    for (let i = idx - 1; i >= 0 && lines[i].trim().startsWith('//'); i--) {
      purpose.unshift(lines[i].trim().replace(/^\/\/\s?/, ''));
    }
    topology[m[1]] = {
      concurrency: num('concurrency'),
      priority: num('priority'),
      attempts: num('attempts'),
      purpose: purpose.join(' '),
    };
  }

  const registeredBlock = text.match(/REGISTERED_QUEUES: readonly QueueName\[\] = \[([\s\S]*?)\] as const;/)[1];
  const registered = [...registeredBlock.matchAll(/QUEUE_NAMES\.([A-Z_]+)/g)].map((m) => m[1]);

  const rows = Object.keys(queueNames).map((key) => {
    const t = topology[key] ?? {};
    return [
      `\`${queueNames[key]}\``,
      registered.includes(key) ? 'Yes' : 'No (declared, not registered)',
      t.concurrency,
      t.priority,
      t.attempts,
      t.purpose,
    ];
  });

  const body = [
    frontmatter(
      'Queues',
      'Every BullMQ queue name, whether it is registered with Nest, and its concurrency, priority, and retry settings.',
    ),
    `Generated from \`nsgdp-backend/src/config/bull.config.ts\`. Queue names are Redis key prefixes. Renaming one orphans jobs already queued under the old name.\n`,
    `Lower priority number runs first. Only registered queues have a worker in the process that registers them.\n`,
    table(['Queue', 'Registered', 'Concurrency', 'Priority', 'Attempts', 'Purpose (from source comment)'], rows),
    '',
  ].join('\n');

  return { name: 'queues.mdx', body, count: Object.keys(queueNames).length };
}

// ----------------------------------------------------------------- tables

function buildTablesPage() {
  const files = walk(join(backend, 'src'), isSource).filter((f) => {
    const s = readFileSync(f, 'utf8');
    return /@Entity\(/.test(s);
  });
  const entries = [];
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(/@Entity\(\s*(?:\{\s*name:\s*)?['"`]([a-z0-9_]+)['"`]/g)) {
      const rel = posix(relative(join(backend, 'src', 'modules'), file));
      const moduleName = rel.startsWith('..') ? posix(relative(join(backend, 'src'), file)).split('/')[0] : rel.split('/')[0];
      entries.push({ table: m[1], module: moduleName, file: posix(relative(backend, file)) });
    }
  }
  entries.sort((a, b) => a.module.localeCompare(b.module) || a.table.localeCompare(b.table));

  const rows = entries.map((e) => [`\`${e.table}\``, e.module, `\`${e.file}\``]);
  const body = [
    frontmatter(
      'Database tables',
      'Every TypeORM entity table in the backend, grouped by module, with its source file.',
    ),
    `Generated from every \`@Entity\` decorator in \`nsgdp-backend/src\`. **${entries.length} tables.** Migrations in \`nsgdp-backend/src/database\` create and change them. The live database can differ if a migration has not run.\n`,
    table(['Table', 'Module', 'Entity file'], rows),
    '',
  ].join('\n');

  return { name: 'tables.mdx', body, count: entries.length };
}

// ----------------------------------------------------------- capabilities

function buildCapabilitiesPage() {
  const file = join(backend, 'src', 'modules', 'admin', 'constants', 'permission-actions.ts');
  const text = readFileSync(file, 'utf8');
  const rows = [];
  for (const m of text.matchAll(
    /'([a-z-]+:[a-z-]+)':\s*\{\s*resourceType:\s*ResourceType\.([A-Z_]+),\s*action:\s*PermissionAction\.([A-Z_]+)/g,
  )) {
    rows.push([`\`${m[1]}\``, m[2].toLowerCase(), m[3].toLowerCase()]);
  }
  const body = [
    frontmatter(
      'Capabilities',
      'Every staff capability key (permission action) and the resource and action it maps to.',
    ),
    `Generated from \`nsgdp-backend/src/modules/admin/constants/permission-actions.ts\`. **${rows.length} capability keys.** Staff hold these through permission groups. Super admins hold all of them. The admin console reads the same keys to show or hide buttons.\n`,
    table(['Capability', 'Resource', 'Action'], rows),
    '',
  ].join('\n');
  return { name: 'capabilities.mdx', body, count: rows.length };
}

// ----------------------------------------------------------------- routes

function routesFor(appRoot) {
  const pages = walk(appRoot, (f) => /[\\/]page\.tsx$/.test(f));
  return pages
    .map((f) => {
      const rel = posix(relative(appRoot, dirname(f)));
      const segments = rel === '' ? [] : rel.split('/').filter((s) => !(s.startsWith('(') && s.endsWith(')')));
      return '/' + segments.join('/');
    })
    .sort();
}

function buildRoutesPage() {
  const sections = [
    ['Public portal and contributor dashboard (nsgdp-frontend)', routesFor(join(frontend, "src", "app"))],
    ['Staff and super admin console (nsgdp-admin)', routesFor(join(admin, "app"))],
  ];
  const parts = [
    frontmatter('Routes', 'Every page route in the frontend and admin apps. Route groups in brackets are removed from the URL.'),
    'Generated from the `page.tsx` files under each app\'s `app/` folder. Route groups such as `(dashboard)` do not appear in the URL, so they are removed here.\n',
  ];
  let total = 0;
  for (const [title, routes] of sections) {
    total += routes.length;
    parts.push(`## ${title}\n`);
    parts.push(`**${routes.length} routes.**\n`);
    parts.push(table(['Route'], routes.map((r) => [`\`${r}\``])));
    parts.push('');
  }
  return { name: 'routes.mdx', body: parts.join('\n'), count: total };
}

// ------------------------------------------------------------------- main

mkdirSync(outDir, { recursive: true });
const results = [buildEnvPage(), buildQueuesPage(), buildTablesPage(), buildCapabilitiesPage(), buildRoutesPage()];
for (const r of results) {
  writeFileSync(join(outDir, r.name), r.body.replace(/\n{3,}/g, '\n\n'), 'utf8');
  console.log(`generated reference/${r.name} (${r.count} rows)`);
}
